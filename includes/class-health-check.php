        return array(
            'primary'        => $primary,
            'fallback'       => $fallback,
            'recommendation' => 'manual_upload',
            'message'        => __( 'Neither URL is working. You may need to manually upload the llms.txt file via SFTP.', 'getcited' ),
        );
    }

