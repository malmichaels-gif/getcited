        if ( defined( 'FLYWHEEL_CONFIG_DIR' ) ) {
            return 'flywheel';
        }

        // Kinsta
        if ( defined( 'KINSTA_CACHE_ZONE' ) ) {
            return 'kinsta';
        }

        return 'standard';
    }

